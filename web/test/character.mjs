import assert from 'node:assert/strict';
import fs from 'node:fs';
import * as THREE from 'three';
import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js';
import { SignalCharacter } from '../public/js/character.js';
import { scribbleSettings } from '../public/js/signal.js';

const bytes = fs.readFileSync(new URL('../public/characters/signal/remy.glb', import.meta.url));
const gltf = await new GLTFLoader().parseAsync(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength), '');
const scene = new THREE.Scene();
const position = new THREE.Vector3(2, 1, -3);
const character = new SignalCharacter(scene, gltf, new THREE.Texture(), { position, yaw: Math.PI / 2 });
const calmEye = character.getEyePosition();
assert(calmEye.toArray().every(Number.isFinite));
assert(calmEye.y > position.y + 1.4 && calmEye.y < position.y + 1.9, 'Standing eye height is plausible');
assert.equal(character.bones.size, 67);
assert.equal(character.scribble.strands.length, 2);
character.update(.1, 0);
assert(character.getEyePosition().distanceTo(calmEye) < 1e-6, 'Calm body stays still');
assert.equal(character.scribble.group.visible, true);
assert(character.scribble.material.opacity >= .6, 'The anxiety line stays visible during calm third-person observation');
const calmLine = character.scribble.strands[0].attributes.position.array.slice();
character.update(.1, 0);
assert(calmLine.some((p, i) => p !== character.scribble.strands[0].attributes.position.array[i]), 'The line keeps moving at zero room intensity');
assert(character.material.uniforms.time.value > 0, 'Text clock advances at zero intensity');
const activeClock = character.material.uniforms.time.value;
character.update(.1, 1);
character.update(.1, 0);
assert(character.material.uniforms.time.value > activeClock, 'Returning to zero does not reset the text');
assert(scribbleSettings(0).speed >= 5, 'The line retains anxious motion at minimum intensity');
character.setEmbodied(true);
const embodiedClock = character.material.uniforms.time.value;
character.update(.1, 0);
assert(character.material.uniforms.time.value > embodiedClock, 'Embodied text also moves at zero intensity');
const embodiedEye = character.getEyePosition();
for (let i = 0; i < 30; i++) character.update(.1, 1, { embodied: true, viewerPosition: embodiedEye });
assert(character.getEyePosition().distanceTo(embodiedEye) < 1e-6, 'Animation does not drive the embodied head');
assert.equal(character.material.uniforms.embodied.value, 1);
assert(character.material.uniforms.clipY.value < embodiedEye.y, 'Head is clipped below viewer eye');
assert.equal(character.scribble.clipUniforms.uSignalEmbodied.value, 1);
assert.equal(character.scribble.material.toneMapped, false);
assert.equal(character.material.toneMapped, false);
assert.equal(character.scribble.group.visible, true);
for (const geometry of character.scribble.strands) assert(geometry.attributes.position.array.every(Number.isFinite));
assert.equal(scribbleSettings(1).radius / scribbleSettings(.2).radius, 2);
assert(scribbleSettings(.21).opacity > 0 && scribbleSettings(.21).opacity < scribbleSettings(1).opacity);
assert(scribbleSettings(1).speed > scribbleSettings(.21).speed);
const before = character.scribble.strands[0].attributes.position.array.slice();
character.update(.1, 1, { viewerPosition: embodiedEye });
assert(before.some((p, i) => p !== character.scribble.strands[0].attributes.position.array[i]), 'Scribbles still animate in first person');
character.reset();
assert.equal(character.material.uniforms.embodied.value, 0);
assert.equal(character.material.uniforms.time.value, 0);
assert.equal(character.scribble.group.visible, true);
character.dispose();
assert.equal(scene.children.length, 0);
console.log('PASS character: skeleton/standing pose, eye handoff, frozen embodied body, head clipping uniforms, two animated thick curves, fade/size/speed, reset/dispose');
